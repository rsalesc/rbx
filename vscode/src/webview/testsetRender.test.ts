test('the card describes the selected testcase and nothing else', () => {
  assert.strictEqual(renderTestsetCard(TREE, state({ selected: 'main' })), '');
  assert.strictEqual(renderTestsetCard(TREE, state()), '');
  const html = renderTestsetCard(TREE, state({ selected: CASE.id }));
  assert.ok(html.includes('<div class="card-title">main/1-gen-000</div>'), html);
  assert.ok(html.includes('<span class="value-label">Input</span>'), html);
  // A generator call names no file, so it is text rather than a link that
  // promises a destination the view cannot reach.
  assert.ok(html.includes('<div class="card-origin" title="Generated by gen 1000 7">'), html);
  assert.ok(html.includes('data-action="rbx.openTestVisualization"'), html);
  assert.ok(html.includes('data-action="panel:gallery"'), html);
});

test('a declared but unbuilt channel offers a lazy button instead', () => {
  // The package was built without `--visualize`, so there is no file to open --
  // but a visualizer is declared, so it can be drawn now.
  const lazy = {
    ...CASE,
    card: {
      ...CASE.card!,
      visualization: undefined,
      answerVisualization: undefined,
      lazyVisualizers: { input: true, output: true },
    },
  };
  const html = renderTestsetCard({ ...TREE, rows: [lazy] }, state({ selected: lazy.id }));
  assert.ok(html.includes('data-action="rbx.visualizeTest"'), html);
  // The Tests view's answer channel is the *expected answer*, not a solution's
  // output, so it has its own command.
  assert.ok(html.includes('data-action="rbx.visualizeTestAnswer"'), html);
  assert.ok(!html.includes('rbx.visualizeSolutionOutput'), html);
  // Marked so the reader can tell it will do work rather than open a file.
  assert.ok(html.includes('class="card-channel lazy"'), html);
});

test('a built channel is never also offered lazily', () => {
  // Built and lazy are exclusive per channel: offering both would put two
  // buttons named `input` side by side.
  const mixed = {
    ...CASE,
    card: {
      ...CASE.card!,
      visualization: 'build/tests/main/visualization/1-gen-000.svg',
      answerVisualization: undefined,
      lazyVisualizers: { input: false, output: true },
    },
  };
  const html = renderTestsetCard(
    { ...TREE, rows: [mixed] },
    state({ selected: mixed.id }),
  );
  assert.ok(html.includes('data-action="rbx.openTestVisualization"'), html);
  assert.ok(!html.includes('data-action="rbx.visualizeTest"'), html);
  assert.ok(html.includes('data-action="rbx.visualizeTestAnswer"'), html);
});

