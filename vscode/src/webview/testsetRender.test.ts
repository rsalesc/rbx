// The fixtures are written as rows rather than run through
// `buildTestsetViewModel`: the renderer's contract is the row, and building one
// from a manifest would make these tests fail for reasons that belong to
// testsetViewModel.test.ts.

function row(over: Partial<TestsetRow> & Pick<TestsetRow, 'id'>): TestsetRow {
  return {
    depth: 0,
    kind: 'group',
    label: over.id,
    meta: [],
    flags: [],
    expandable: false,
    defaultExpanded: false,
    search: (over.label ?? over.id).toLowerCase(),
    section: 'rbx.testsetGroup',
    ...over,
  };
}

function model(rows: readonly TestsetRow[]): TestsetViewModel {
  return { rows, empty: false, header: { built: 'built 3m ago', summary: '2 tests · 1 group' } };
}

function state(over: Partial<TestsetUiState> = {}): TestsetUiState {
  return { expanded: new Set<string>(), filter: '', ...over };
}

const MAIN = row({
  id: 'main',
  kind: 'group',
  label: 'main',
  meta: [
    { text: '[60/100]', hue: 'dim', role: 'score' },
    { text: '2 tests', hue: 'dim', role: 'count' },
  ],
  expandable: true,
  defaultExpanded: true,
});

const CASE = row({
  id: 'main::1-gen-000',
  parentId: 'main',
  depth: 1,
  kind: 'testcase',
  label: '1-gen-000',
  meta: [{ text: '4 KiB', hue: 'dim', role: 'size' }],
  flags: [{ kind: 'visualization', hue: 'blue', title: 'Has a visualization' }],
  search: 'main/1-gen-000 gen 1000',
  section: 'rbx.testsetTestcase',
  primaryCommand: 'rbx.openBuiltTestcase',
  card: {
    title: 'main/1-gen-000',
    origins: [{ text: 'gen 1000 7', title: 'Generated by gen 1000 7' }],
    values: [{ label: 'Input', text: '4 KiB' }],
    visualization: 'build/tests/main/visualization/1-gen-000.svg',
    lazyVisualizers: { input: false, output: false },
  },
});

const REJECTED = row({
  id: 'main::1-gen-001',
  parentId: 'main',
  depth: 1,
  kind: 'testcase',
  label: '1-gen-001',
  flags: [{ kind: 'invalid', hue: 'red', title: 'n must be at most 100' }],
  search: 'main/1-gen-001 invalid',
  section: 'rbx.testsetTestcase',
  primaryCommand: 'rbx.openBuiltTestcase',
  card: {
    title: 'main/1-gen-001',
    origins: [],
    values: [],
    lazyVisualizers: { input: false, output: false },
    validation: {
      ok: false,
      hue: 'red',
      text: 'Rejected by the validator',
      validator: 'validator.cpp',
      message: 'n must be at most 100',
    },
  },
});

const TREE = model([MAIN, CASE, REJECTED]);
const OPEN = state({ expanded: new Set(['main']) });

test('a group row is a tree item with a twisty, a meta line and a marks cell', () => {
  const html = renderTestsetTree(TREE, OPEN);
  assert.ok(html.includes('class="row testset-row kind-group"'), html);
  assert.ok(html.includes('<span class="twisty codicon codicon-chevron-down"></span>'), html);
  assert.ok(html.includes('<span class="span span-score hue-dim">[60/100]</span>'), html);
  assert.ok(html.includes('<span class="span span-count hue-dim">2 tests</span>'), html);
  // The marks cell exists on every row, empty or not, so the column can be
  // scanned straight down.
  assert.strictEqual(html.match(/class="flags"/g)?.length, 3);
});

test('the separators are drawn by the stylesheet, never emitted between spans', () => {
  const html = renderTestsetTree(TREE, OPEN);
  assert.ok(html.includes('[60/100]</span><span class="span span-count'), html);
});

test('a mark carries its own hue and its reason as the hover', () => {
  const html = renderTestsetTree(TREE, OPEN);
  assert.ok(
    html.includes(
      '<span class="flag flag-visualization hue-blue" title="Has a visualization">' +
        '<span class="codicon codicon-file-media"></span></span>',
    ),
    html,
  );
  assert.ok(
    html.includes(
      '<span class="flag flag-invalid hue-red" title="n must be at most 100">' +
        '<span class="codicon codicon-warning"></span></span>',
    ),
    html,
  );
});

test('every row announces its place in the tree, and only parents announce expansion', () => {
  const html = renderTestsetTree(TREE, OPEN);
  assert.ok(html.includes('aria-level="1" aria-setsize="1" aria-posinset="1"'), html);
  assert.ok(html.includes('aria-level="2" aria-setsize="2" aria-posinset="2"'), html);
  // Absent, not false, on a leaf: `aria-expanded="false"` on a childless node
  // tells a screen reader there is something to open.
  assert.strictEqual(html.match(/aria-expanded/g)?.length, 1);
});

test('exactly one row holds the tab stop', () => {
  const html = renderTestsetTree(TREE, state({ expanded: new Set(['main']), selected: CASE.id }));
  assert.strictEqual(html.match(/tabindex="0"/g)?.length, 1);
  assert.ok(html.includes(`data-id="main::1-gen-000"`), html);
  // With nothing selected the first row stands in, so a Tab into the view lands
  // somewhere useful.
  assert.ok(renderTestsetTree(TREE, OPEN).indexOf('tabindex="0"') < 200);
});

test('a row carries the section its context menu keys on', () => {
  const html = renderTestsetTree(TREE, OPEN);
  assert.ok(html.includes('&quot;webviewSection&quot;:&quot;rbx.testsetGroup&quot;'), html);
  assert.ok(html.includes('&quot;webviewSection&quot;:&quot;rbx.testsetTestcase&quot;'), html);
  assert.ok(html.includes('&quot;preventDefaultContextMenuItems&quot;:true'), html);
});

test('a collapsed group hides its tests', () => {
  const html = renderTestsetTree(TREE, state());
  assert.ok(html.includes('data-id="main"'), html);
  assert.ok(!html.includes('1-gen-000'), html);
});

test('a filter keeps the group of a matching test, and the tests of a matching group', () => {
  const byStem = visibleTestsetRows(TREE, state({ expanded: new Set(['main']), filter: '001' }));
  assert.deepStrictEqual(byStem.map((r) => r.id), ['main', 'main::1-gen-001']);
  const byGroup = visibleTestsetRows(TREE, state({ expanded: new Set(['main']), filter: 'main' }));
  assert.deepStrictEqual(byGroup.map((r) => r.id), ['main', 'main::1-gen-000', 'main::1-gen-001']);
  // A filter narrows what is visible; it never opens what the user closed.
  assert.deepStrictEqual(
    visibleTestsetRows(TREE, state({ filter: '001' })).map((r) => r.id),
    ['main'],
  );
});

test('the filter reads the haystack the view model built, and nothing else', () => {
  assert.ok(matchesTestsetFilter(REJECTED, 'INVALID'));
  assert.ok(matchesTestsetFilter(CASE, ' gen '.trim()));
  assert.ok(!matchesTestsetFilter(CASE, 'invalid'));
  assert.ok(matchesTestsetFilter(CASE, ''));
});

