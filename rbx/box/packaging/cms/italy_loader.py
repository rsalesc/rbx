"""What CMS's Italian YAML importer (`cmscontrib/loaders/italy_yaml.py`) reads.

Only the contest goes this way. Its tasks come from the Polygon packages that
`--cms` builds, because CMS compiles their checker and manager when it imports
them, on its own machine; the Italian loader would need them already compiled.
So the tasks are imported first, unattached, with `cmsImportTask`, and the
contest then attaches them by name.

That is why each task listed in `contest.yaml` gets a stub `<task>/task.yaml`:
`cmsImportContest` asks the Italian loader whether a task already in the
database has changed, and the loader exits when the task has no `task.yaml`.
The stub has no `.itime`, so it always answers that the task changed, and
`cmsImportContest` only warns that it is not updating it -- unless it is run
with `--import-tasks` or `--update-tasks`, which would load the stub as a task.
"""

import pathlib
from typing import Any, Dict, List, Tuple

import yaml

from rbx.box import environment, naming
from rbx.box.contest.schema import Contest
from rbx.box.packaging.cms import settings
from rbx.box.packaging.cms.extension import CmsExtension, CmsLanguageExtension

CONTEST_FILE = 'contest.yaml'
TASK_STUB_FILE = 'task.yaml'

_TASK_STUB = (
    '# Generated by rbx. Not a task: the task itself is imported from its Polygon\n'
    '# package with cmsImportTask. This file only lets cmsImportContest attach it.\n'
    'name: {name}\n'
)


def contest_languages() -> Tuple[List[str], List[str]]:
    """The CMS languages of the environment, and the rbx languages with none.

    The CMS languages come in `env.rbx.yml` order, each once.
    """
    cms_languages: Dict[str, None] = {}
    unmapped = []
    for language in environment.get_environment().languages:
        extension = language.get_extension_or_default('cms', CmsLanguageExtension)
        if not extension.languages:
            unmapped.append(language.name)
            continue
        for cms_language in extension.languages:
            cms_languages.setdefault(cms_language, None)
    return list(cms_languages), unmapped


def _description(contest: Contest) -> str:
    language = None
    if contest.statements:
        language = contest.statements[0].language
    elif contest.titles:
        language = next(iter(contest.titles))
    return naming.get_contest_title(language, contest=contest)


def contest_conf(
    contest: Contest, cms_settings: CmsExtension, languages: List[str]
) -> Dict[str, Any]:
    """The `contest.yaml` of `contest`, as a dict."""
    conf: Dict[str, Any] = {
        'name': contest.name,
        'description': _description(contest),
    }
    if languages:
        conf['languages'] = languages
    conf.update(settings.contest_keys(cms_settings.contest))
    # Without `token_mode`, the loader reads a deprecated format that turns tokens
    # off. `infinite` is CMS's own default, which leaves the decision to each task.
    conf.setdefault('token_mode', 'infinite')
    conf['tasks'] = [problem.short_name for problem in contest.problems]
    return conf


def write_contest(
    into_path: pathlib.Path,
    contest: Contest,
    cms_settings: CmsExtension,
    languages: List[str],
):
    """Write `contest.yaml`, and a stub per task, into `into_path`."""
    into_path.mkdir(parents=True, exist_ok=True)
    conf = contest_conf(contest, cms_settings, languages)
    (into_path / CONTEST_FILE).write_text(
        yaml.safe_dump(conf, sort_keys=False, allow_unicode=True)
    )
    for task in conf['tasks']:
        stub = into_path / task / TASK_STUB_FILE
        stub.parent.mkdir(parents=True, exist_ok=True)
        stub.write_text(_TASK_STUB.format(name=task))
