#!/bin/bash
# ---------------------------------------------------------------------------
# rbx MOJ interactive driver: mojtools' own driver (interactive/run.sh, embedded
# verbatim below), plus one rule it does not have.
#
# mojtools lets the arbiter's verdict win over how the contestant ended: a
# contestant that crashes is Wrong Answer (the arbiter then complains about end
# of file), and one that answers correctly and then crashes is Accepted. rbx,
# Polygon and DOMjudge call both Runtime Error. So once the driver is done, if
# the contestant exited non-zero or died of a signal other than SIGPIPE (which
# it only gets because the arbiter left first), then
#   - an arbiter result that is not `WRONG ...` becomes Runtime Error;
#   - a `WRONG ...` that only complains about end of file becomes Runtime Error.
# Any other `WRONG` stays Wrong Answer. See rsalesc/rbx#895.
#
# The jail binds only this one file, so the driver cannot be a sibling file: it
# is written to /tmp and run from there.
#
# Generated by rbx -- do not edit by hand.
# ---------------------------------------------------------------------------

cat > /tmp/rbx-mojtools-run.sh <<'RBX_MOJTOOLS_DRIVER_EOF'
{{mojtoolsDriver}}
RBX_MOJTOOLS_DRIVER_EOF

# The time limit arrives as TERM, normally to the whole process group (so the
# driver gets its own); forward it in case only this shell got it. After a TERM
# the verdict is the time limit's, so the rule below must not touch it.
termed=0
driver=
trap 'termed=1; [[ -n "$driver" ]] && kill -TERM "$driver" 2>/dev/null' TERM
bash /tmp/rbx-mojtools-run.sh &
driver=$!
while true; do
  wait "$driver"
  rc=$?
  # A trapped signal makes `wait` return early (status > 128) with the driver
  # still running; wait for it again.
  kill -0 "$driver" 2>/dev/null || break
done
(( rc == 0 && ! termed )) || exit "$rc"

# Only when the arbiter itself ended normally: every other way out was already
# decided by the driver.
grep -Eqi '(non-zero|signal)' /tmp/arbitro.time 2>/dev/null && exit 0
grep -Eqi '(non-zero|signal)' /tmp/aluno.time 2>/dev/null || exit 0
alunosig="$(grep -i 'terminated by signal' /tmp/aluno.time 2>/dev/null | grep -oE '[0-9]+' | head -1)"
[[ "$alunosig" == 13 ]] && exit 0
[[ -s /tmp/out ]] || exit 0

resultado="$(grep -v '^[[:space:]]*$' /tmp/out | tail -n1)"
if [[ "$resultado" != WRONG* ]]; then
  echo "DRIVER(rbx): arbiter accepted, but the contestant ended with an error -> Runtime Error" >> /tmp/stderrlog
  exit 3
fi
if grep -qi 'unexpected end of file' <<< "$resultado"; then
  echo "DRIVER(rbx): the contestant died and the arbiter only complained about end of file -> Runtime Error" >> /tmp/stderrlog
  exit 3
fi
exit 0
